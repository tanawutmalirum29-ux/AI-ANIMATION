import handler, github_oauth, guest_access

ENV={"GITHUB_OAUTH_CLIENT_ID":"test-client",
     "GITHUB_OAUTH_SECRET_PARAMETER":"/test/oauth",
     "SESSION_SECRET":"long-dev-secret-for-production-parity-not-a-real-secret",
     "CLOUD_EXPORT_BUCKET":"test-studio-export",
     "CLOUD_EXPORT_PROJECT":"test-codebuild-project"}

def parse(out):return out["statusCode"],json.loads(out["body"])
def event(action,token,**rest):
    return {"body":json.dumps({"action":action,**rest}),
            "headers":{"authorization":"Bearer "+token}}

class FakeS3:
    def __init__(self):self.records={}
    def put_object(self,**kw):
        self.records[kw["Key"]]=kw
        return {}
    def head_object(self,**kw):
        key=kw["Key"]
        if key not in self.records:
            raise FakeClientError("NoSuchKey")
        return {"Metadata":self.records[key].get("Metadata",{}),
                "ContentLength":100}
    def generate_presigned_url(self,operation,Params,ExpiresIn):
        return "https://s3.example.invalid/signed"
    def get_object(self,**kw):
        raise FakeClientError("NoSuchKey")

class FakeClientError(Exception):
    def __init__(self,code):
        self.response={"Error":{"Code":code}}
class FakeBuild:
    def start_build(self,**kw):return {"build":{"id":"sample-build"}}
    def batch_get_builds(self,ids):return {"builds":[{"buildStatus":"IN_PROGRESS"}]}
    def stop_build(self,id):return {}

class EditorAccessTests(unittest.TestCase):
    def test_guest_and_member_use_synth_from_normal_editor(self):
        with mock.patch.dict(os.environ,ENV),\
             mock.patch.object(handler,"_synth",return_value=b"test-audio"):
            guest=guest_access.start()
            guest_token=json.loads(guest["body"])["token"]
            member_token,_=github_oauth.issue_session({"id":1111,"login":"ordinary"})
            for token in (guest_token,member_token):
                status,reply=parse(handler.handler(event(
                    "synthesize",token,text="พากย์ข้อความสำหรับฉาก"),None))
                self.assertEqual(status,200,reply)
                self.assertIn("audio",reply)
                for action in ("teacher.advisorStatus","teacher.autoLessons",
                               "teacher.job.list","teacher.connection.list",
                               "member.keys.list","student.train","editor.review"):
                    self.assertEqual(handler.handler(event(action,token),None)["statusCode"],403,action)

    def test_nonadmin_exports_are_owner_scoped_admin_remains_compatible(self):
        fake_s3=FakeS3()
        botocore=types.ModuleType("botocore")
        exceptions=types.ModuleType("botocore.exceptions")
        exceptions.ClientError=FakeClientError
        botocore.exceptions=exceptions
        with mock.patch.dict(os.environ,ENV),\
             mock.patch.dict(sys.modules,{"botocore":botocore,"botocore.exceptions":exceptions}),\
             mock.patch.object(handler,"_export_s3_client",return_value=fake_s3):
            boto3=types.ModuleType("boto3")
            boto3.client=lambda name:FakeBuild()
            with mock.patch.dict(sys.modules,{"boto3":boto3}):
                tokens={}
                tokens["guest"]=json.loads(guest_access.start()["body"])["token"]
                tokens["member"],_=github_oauth.issue_session({"id":11,"login":"member"})
                tokens["other"],_=github_oauth.issue_session({"id":12,"login":"other"})
                tokens["admin"],_=github_oauth.issue_session({"id":225819900,"login":"owner"})
                import uuid
                # Test owner-bound export marker via exact UUID generated by prepare.
                with mock.patch.object(uuid,"uuid4",return_value=uuid.UUID(
                   "a141b2c3-d4e5-4fab-89ac-7de12345a678")):
                    status,result=parse(handler.handler(event("export.prepare",tokens["member"]),None))
                self.assertEqual(status,200,result)
                jid=result["jobId"]
                self.assertTrue(fake_s3.records["jobs/"+jid+"/prepared"]["Metadata"].get("owner"))
                status,_=parse(handler.handler(event("export.status",tokens["other"],jobId=jid),None))
                self.assertEqual(status,403)
                status,_=parse(handler.handler(event("export.cancel",tokens["guest"],jobId=jid),None))
                self.assertEqual(status,403)
                status,_=parse(handler.handler(event("export.start",tokens["member"],jobId=jid),None))
                self.assertIn(status,(200,400))
                status,_=parse(handler.handler(event("export.status",tokens["admin"],jobId=jid),None))
                self.assertEqual(status,200)

if __name__=="__main__":unittest.main()
