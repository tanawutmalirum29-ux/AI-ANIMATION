const assert=require('node:assert/strict');
const planner=require('../studio-episode-planner.js');
const text='คืนหนึ่งฝนตกหนัก เด็กหญิงเดินเข้าป่าเพื่อหาหนังสือที่หายไป。 เธอได้ยินเสียงเคาะประตู จึงหยุดเดินและตั้งใจฟัง！\n\n'
  .repeat(28)+'ในที่สุดเธอก็พบประตูที่มีแสงสว่างอยู่ด้านหลัง';
const plan=planner.plan(text,{targetMinutes:1,charsPerSecond:6.5});
assert.ok(plan.episodes.length>=2,'long scripts must become multiple episodes');
assert.ok(plan.episodes.every(e=>e.targetSeconds===60&&e.scenes.length>0));
assert.ok(plan.episodes.every(e=>e.scenes.every(s=>s.duration>0&&s.duration<50)));
const scenes=plan.episodes.flatMap(ep=>ep.scenes);
assert.equal(scenes.length,plan.totalScenes);
assert.equal(scenes.map(s=>s.voiceover).join(' ').replace(/\s/g,''),text.replace(/\s/g,''),'must preserve all authored content');
assert.equal(new Set(scenes.map(s=>s.id)).size,scenes.length,'scene IDs unique');
assert.ok(scenes.every(s=>s.subtitle.length===0),'no permanent captions blocking video');
assert.ok(scenes.every(s=>s.subtitleCues.every(c=>Array.from(c.text).length<=28&&c.start>=0&&c.end<=s.duration+.01)));
assert.ok(scenes.every(s=>s.subtitleCues.at(-1).end===s.duration));
const tiny=planner.plan('เรื่องสั้นจบแล้ว',{targetMinutes:20});
assert.equal(tiny.episodes.length,1,'do not pad a short script with fake time');
assert.ok(tiny.totalSeconds<60,'duration is an estimate, not forced to requested target');
assert.throws(()=>planner.plan(''),/ไม่มีบท/);
assert.throws(()=>planner.plan('abc',{targetMinutes:45}),/1–30/);
assert.throws(()=>planner.plan('ว'.repeat(60001)),/60,000/);
const thai=planner.plan('ภาษาไทยไม่มีการเว้นช่องว่างระหว่างคำหลายคำติดต่อกัน'.repeat(200),{targetMinutes:1});
assert.equal(thai.episodes.flatMap(e=>e.scenes.map(s=>s.voiceover)).join('').replace(/\s/g,''),'ภาษาไทยไม่มีการเว้นช่องว่างระหว่างคำหลายคำติดต่อกัน'.repeat(200));
console.log('PASS: Thai paragraphs, sentence timing, no lost words, capped subtitles, distinct episodes, no artificial padding');
