'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const assets = require('../studio-production-assets.js');
const core = require('../studio-asset-core.js');
const planner = require('../studio-production-planner.js');
const {validate} = require('../training-lab/validate-story.cjs');
const doc = JSON.parse(fs.readFileSync(path.join(__dirname,'../examples/taweetha-zombie-siege.json'),'utf8'));
const report = validate(doc);
assert.equal(report.ok,true,JSON.stringify(report.errors));
assert.equal(doc.episodes.length,1);
const scenes = doc.episodes[0].scenes;
assert.equal(scenes.length,12);
assert.equal(scenes.reduce((sum,s)=>sum+s.duration,0),62);
assert.equal(doc.project.aspect,'9:16');
assert.equal(doc.voiceProfiles.length,4);
assert.ok(scenes.every(s=>s.voiceDirection?.voiceProfileId));
assert.ok(scenes.every(s=>s.productionEvents.every(k=>assets.templates[k])));
assert.ok(scenes.every(s=>s.customAssets.length<=40));
for(const s of scenes){
 for(const item of s.customAssets){assert.doesNotThrow(()=>core.asset(item.asset));assert.ok(item.x>=0&&item.x<=100);}
 assert.equal(planner.plan({episodes:[{scenes:[s]}]},'assets',assets).ops.length,0,'no duplicate automatic assets in '+s.id);
}
assert.ok(scenes.find(s=>s.id==='tpz-s06').customAssets.find(a=>a.eventKind==='school-barricade').motionKeys.length>=3);
assert.ok(scenes.find(s=>s.id==='tpz-s07').customAssets.find(a=>a.eventKind==='school-window').motionKeys.some(k=>k.opacity===0));
const blank={episodes:[{scenes:[{id:'new-school',duration:5,voiceover:'',productionEvents:['school-barricade','school-alarm'],productionPlacements:{'school-barricade':{x:25,y:80,scale:.4}},customAssets:[]}]}]};
const planned=planner.plan(blank,'assets',assets);
assert.equal(planned.ops.length,1);
assert.equal(planned.ops[0].patch.customAssets.length,2);
assert.equal(planned.ops[0].patch.customAssets[0].x,25);
assert.equal(planned.ops[0].patch.customAssets[0].scale,.4);
assert.doesNotThrow(()=>core.asset(planned.ops[0].patch.customAssets[0].asset));
blank.episodes[0].scenes[0].customAssets=planned.ops[0].patch.customAssets;
assert.equal(planner.plan(blank,'assets',assets).ops.length,0);

const world = require('../studio-school-world.js');
const expectedWorld=['school-front','school-yard','school-hall','school-room','school-stairs','school-roof'];
assert.deepEqual([...world.TYPES],expectedWorld);
for(const location of doc.locations){
 const svg=world.render(location.set,'back',50.625,2.5,{});
 assert.ok(svg.includes('<rect')&&svg.length>1000,'full-bleed world '+location.id);
 assert.equal(world.render(location.set,'front',50.625,2.5,{}),'','scenery never overlays actors');
}
const environmentKinds=new Set(['school-facade','school-gate','school-courtyard','school-corridor','school-classroom','school-stairs','school-rooftop','school-window','school-door','school-zombie']);
assert.ok(scenes.every(s=>s.customAssets.every(item=>!environmentKinds.has(item.eventKind))),'no duplicates of backdrop, door or zombie rig');
assert.ok(scenes.every(s=>s.camera.world===1),'no oversized panorama crops');
assert.ok(scenes.every(s=>s.atmosphere!=='wind'),'no stray wind strokes over characters');
const state={project:doc.project,episodes:doc.episodes};
assert.equal(planner.plan(state,'assets',assets).ops.length,0,'story assets remain idempotent');
const room5=scenes.find(s=>s.id==='tpz-s05'),roof9=scenes.find(s=>s.id==='tpz-s09'),roof10=scenes.find(s=>s.id==='tpz-s10'),roof12=scenes.find(s=>s.id==='tpz-s12');
assert.ok(world.render(doc.locations.find(x=>x.id==='classroom').set,'back',50,0,room5).includes('rect'));
assert.notEqual(world.render(doc.locations.find(x=>x.id==='classroom').set,'back',50,0,room5),world.render(doc.locations.find(x=>x.id==='classroom').set,'back',50,5,room5),'classroom door visibly closes');
assert.equal(world.render(doc.locations.find(x=>x.id==='rooftop').set,'back',50,0,roof9),world.render(doc.locations.find(x=>x.id==='rooftop').set,'back',50,5,roof9),'locked roof door remains closed');
assert.notEqual(world.render(doc.locations.find(x=>x.id==='rooftop').set,'back',50,0,roof10),world.render(doc.locations.find(x=>x.id==='rooftop').set,'back',50,5,roof10),'roof door opens after key unlocks');
assert.notEqual(world.render(doc.locations.find(x=>x.id==='rooftop').set,'back',50,0,roof12),world.render(doc.locations.find(x=>x.id==='rooftop').set,'back',50,5,roof12),'roof door opens before finale reveal');
const finaleZombie=roof12.actors.find(a=>a.char==='zombie');
assert.ok(finaleZombie.appearAt>=4&&finaleZombie.motionKeys[1].t>=finaleZombie.appearAt,'zombie enters only after door starts opening');
assert.ok(scenes.every(s=>s.actors.every(a=>a.scale<=.85)),'consistent portrait character scale');
const timedActors=scenes.flatMap(s=>s.actors).filter(a=>a.motionKeys?.length>0);
assert.ok(timedActors.length>=9,'authored run and walk intervals');
assert.ok(timedActors.every(a=>a.motionKeys.every((k,i,q)=>i===0||k.t>=q[i-1].t)),'sorted motion keys');
const barricade=scenes.find(s=>s.id==='tpz-s06').customAssets.find(a=>a.eventKind==='school-barricade');
assert.equal(barricade.front,false,'barricade must sit behind actor silhouettes');
assert.ok(barricade.scale<=.45,'avoid oversized desk covering actors');
assert.ok(barricade.motionKeys.at(-1).x===53,'barricade stops in front of closed door');
const validPoses=new Set(['stand','walk','run','sit','point','wave','think','talk','cheer','jump','typing','carry','openDoor','handshake','sad','surprised']);
const validFaces=new Set(['neutral','happy','sad','surprised','angry','think','sleep','talk']);
assert.ok(scenes.every(s=>s.actors.every(a=>validPoses.has(a.pose)&&validFaces.has(a.face))),'supported rigs and expressions');
assert.ok(doc.characters.find(x=>x.id==='mind').rig.hairStyle==='ponytail','Mind must look different from Nont');
console.log('PASS: refreshed 12-scene 62-second school zombie movie; full-bleed world; correct layering; run timing; door + finale cues');
